// Pure input helpers shared by the routes (unit tested in test/).

export const MAX = {
  message: 4000,
  displayName: 100,
  sourcePage: 512,
  idempotencyKey: 128,
  externalRef: 200,
  visitorIdMin: 16,
  visitorIdMax: 128,
} as const;

// PostgreSQL text cannot hold NUL; reject it (and other control characters
// that have no place in chat text) instead of failing with a 500 later.
// Tab, LF and CR are allowed.
const BAD_CONTROL = /[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/;

export function isCleanText(value: string): boolean {
  return !BAD_CONTROL.test(value);
}

// The visitor credential is a random token generated by the widget. A minimum
// length keeps it unguessable; the charset keeps it safe to log-free store.
export function isVisitorId(value: unknown): value is string {
  return (
    typeof value === "string" &&
    value.length >= MAX.visitorIdMin &&
    value.length <= MAX.visitorIdMax &&
    /^[A-Za-z0-9_-]+$/.test(value)
  );
}

// Origin + path only: query strings and fragments can carry personal data and
// are never stored. Returns null for anything that is not an http(s) URL.
export function normalizeSourcePage(value: unknown): string | null {
  if (typeof value !== "string" || value.length === 0 || value.length > MAX.sourcePage) return null;
  try {
    const u = new URL(value);
    if (!/^https?:$/.test(u.protocol)) return null;
    return (u.origin + u.pathname).slice(0, MAX.sourcePage);
  } catch {
    return null;
  }
}

export type TextCheck = { ok: true; value: string } | { ok: false; error: string };

// Required, trimmed, length-capped chat text.
export function checkText(field: string, value: unknown, max: number): TextCheck {
  if (typeof value !== "string") return { ok: false, error: `${field} must be a string` };
  const trimmed = value.trim();
  if (trimmed.length === 0) return { ok: false, error: `${field} must not be empty` };
  if (value.length > max) return { ok: false, error: `${field} is too long (max ${max})` };
  if (!isCleanText(value)) return { ok: false, error: `${field} contains invalid characters` };
  return { ok: true, value: trimmed };
}

export function checkOptionalKey(field: string, value: unknown, max: number): TextCheck | null {
  if (value === undefined || value === null) return null;
  return checkText(field, value, max);
}

export function parseId(value: unknown): number | null {
  const n = Number(value);
  return Number.isSafeInteger(n) && n > 0 ? n : null;
}
